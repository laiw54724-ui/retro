import { copyFile, mkdir, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const source = fileURLToPath(new URL("../../../windows98-icons/png/", import.meta.url));
const destination = fileURLToPath(new URL("../public/win98-icons/", import.meta.url));
const manifestPath = fileURLToPath(new URL("../src/lib/win98IconManifest.ts", import.meta.url));
const files = (await readdir(source)).filter((file) => file.toLowerCase().endsWith(".png")).sort((a, b) => a.localeCompare(b));

await mkdir(destination, { recursive: true });
await Promise.all(files.map((file) => copyFile(path.join(source, file), path.join(destination, file))));

const label = (file) => file.replace(/\.png$/i, "").replace(/[_-]+/g, " ").replace(/\s+/g, " ").trim();
const records = files.map((file) => ({ key: file.replace(/\.png$/i, ""), label: label(file), path: `/win98-icons/${file}` }));
const preferred = /(computer|desktop|directory|folder|document|file|camera|photo|image|mail|message|internet|world|network|music|sound|user|address|game|paint|palette|trash|recycle|search|help|book|calendar|clock|phone|key|home|star|heart|link)/i;
const ranked = [...records].sort((a, b) => {
  const score = (item) => (preferred.test(item.key) ? 4 : 0) + (/(?:-0|-1)$/.test(item.key) ? 2 : 0) + (!/-\d+$/.test(item.key) ? 1 : 0);
  return score(b) - score(a) || a.key.localeCompare(b.key);
});
const curated = ranked.slice(0, 120).map((record) => record.key);
const sourceText = `// Generated by scripts/import-win98-icons.mjs from the user-supplied PNG library.\n` +
  `export type Win98IconRecord = { key: string; label: string; path: string };\n` +
  `export const WIN98_ICON_RECORDS: Win98IconRecord[] = ${JSON.stringify(records, null, 2)};\n` +
  `export const CURATED_WIN98_ICON_KEYS = new Set(${JSON.stringify(curated, null, 2)});\n`;
await writeFile(manifestPath, sourceText);
console.log(`Imported ${records.length} Win98 PNG icons; curated ${curated.length}.`);
